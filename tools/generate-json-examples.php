/**
 * Führt den SDK-Aufruf gegen einen Mock aus und liefert Methode, Pfad und Body des Requests.
 *
 * @param Closure(BillomatClient): mixed $call
 *
 * @return array{string, string, string}
 */
function capture(Closure $call): array
{
    $captured = null;
    $mock = new MockHttpClient(static function (string $method, string $url, array $options) use (&$captured): MockResponse {
        $path = substr((string) parse_url($url, PHP_URL_PATH), \strlen('/api'));
        $body = $options['body'] ?? '';
        $captured = [$method, $path, \is_string($body) ? $body : ''];

        // Minimale Antwort, damit die Hydration des Rückgabewerts klappt.
        $slug = explode('/', $path)[1] ?? '';
        $key = 'settings' === $slug ? 'settings' : (string) preg_replace(['/ies$/', '/(x)es$/', '/s$/'], ['y', '$1', ''], $slug);

        return new MockResponse((string) json_encode([$key => ['id' => '1', 'unit_price' => '0', 'amount' => '0', 'name' => 'x', 'filename' => 'x', 'mime_type' => 'x', 'filesize' => '1', 'created' => '2026-11-02T00:00:00+01:00']]));
    });

    $call(new BillomatClient(new BillomatConfig(billomatId: 'mycompany', apiKey: 'example'), new Psr18Client($mock)));

    if (null === $captured) {
        throw new RuntimeException('Kein Request mitgeschnitten.');
    }

    return $captured;
}

function prettyJson(string $json): string
{
    return json_encode(json_decode($json, true, flags: JSON_THROW_ON_ERROR), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR)."\n";
}

/**
 * Hat die Listen-Fixture mindestens einen Eintrag?
 */
function hasRows(string $file): bool
{
    $data = json_decode((string) file_get_contents($file), true, flags: JSON_THROW_ON_ERROR);
    $envelope = \is_array($data) ? reset($data) : null;
    if (!\is_array($envelope)) {
        return false;
    }

    return [] !== array_filter(array_keys($envelope), static fn (int|string $key): bool => !str_starts_with((string) $key, '@'));
}

/**
 * @param array<string, array{string, string}> $requestLabels Snippet-Name → [Methode, Pfad]
 * @param list<string>                         $tabs
 */
function section(array $requestLabels, array $tabs): ?string
{
    $lines = [];
    foreach ($tabs as $tab) {
        if (isset($requestLabels[$tab])) {
            [$method, $path] = $requestLabels[$tab];
            $lines[] = "<<< @/snippets/json/{$tab}.json [{$method} {$path}]";

            continue;
        }

        [$resource, $kind] = explode('/', $tab);
        $file = FIXTURE_DIR."/{$resource}/{$kind}.json";
        if (!is_file($file) || ('list' === $kind && !hasRows($file))) {
            continue;
        }
        $label = 'get' === $kind ? ('settings' === $resource ? "GET /{$resource}" : "GET /{$resource}/{id}") : "GET /{$resource}";
        $lines[] = "<<< @/../tests/Fixtures/Contract/{$resource}/{$kind}.json [{$label} (response)]";
    }

    if ([] === $lines) {
        return null;
    }

    return implode("\n", [
        START,
        '## JSON on the wire',
        '',
        "Billomat's API documentation only shows XML. These are the JSON bodies the SDK sends and receives: requests as the SDK serializes them, responses recorded in the Billomat sandbox and anonymized ([contract fixtures](../../tests/Fixtures/Contract)). Billomat sends every value as a string; the read models cast them (see [Read models](../concepts/models.md)).",
        '',
        '::: code-group',
        ...$lines,
        ':::',
        END,
    ]);
}

function updatePage(string $markdown, ?string $section): string
{
    $start = strpos($markdown, START);
    if (false !== $start) {
        $end = strpos($markdown, END, $start);
        if (false === $end) {
            throw new RuntimeException('Endmarker fehlt.');
        }
        $before = rtrim(substr($markdown, 0, $start))."\n\n";
        $after = ltrim(substr($markdown, $end + \strlen(END)));

        return null === $section ? rtrim($before)."\n".('' === $after ? '' : "\n".$after) : $before.$section."\n".('' === $after ? '' : "\n".$after);
    }

    if (null === $section) {
        return $markdown;
    }

    $pitfalls = strpos($markdown, "\n## Pitfalls\n");
    if (false !== $pitfalls) {
        return substr($markdown, 0, $pitfalls)."\n".$section."\n".substr($markdown, $pitfalls);
    }

    return rtrim($markdown)."\n\n".$section."\n";
}

$check = \in_array('--check', $argv, true);
$outdated = [];
$written = [];

$requestLabels = [];
foreach (requests() as $name => $call) {
    [$method, $path, $body] = capture($call);
    $requestLabels[$name] = [$method, $path];
    $file = SNIPPET_DIR."/{$name}.json";
    $json = prettyJson($body);
    if (!is_file($file) || file_get_contents($file) !== $json) {
        $outdated[] = $file;
        if (!$check) {
            if (!is_dir(SNIPPET_DIR)) {
                mkdir(SNIPPET_DIR, 0o777, true);
            }
            file_put_contents($file, $json);
        }
    }
    $written[] = basename($file);
}

foreach (glob(SNIPPET_DIR.'/*.json') ?: [] as $file) {
    if (!\in_array(basename($file), $written, true)) {
        $outdated[] = $file;
        if (!$check) {
            unlink($file);
        }
    }
}

foreach (PAGES as $page => $tabs) {
    $file = PROJECT_ROOT."/docs/resources/{$page}.md";
    $markdown = (string) file_get_contents($file);
    $updated = updatePage($markdown, section($requestLabels, $tabs));
    if ($updated !== $markdown) {
        $outdated[] = $file;
        if (!$check) {
            file_put_contents($file, $updated);
        }
    }
}

foreach ($outdated as $file) {
    echo ($check ? 'veraltet: ' : 'geschrieben: ').substr($file, \strlen(PROJECT_ROOT) + 1)."\n";
}

if ($check && [] !== $outdated) {
    echo "JSON-Beispiele sind veraltet, bitte `composer docs:json` ausführen.\n";
    exit(1);
}

if ($check) {
    echo "JSON-Beispiele sind aktuell.\n";
}
